def process_ai_command(user_input, context="", conversation_history=None):
    """Process user voice or text input using Gemini."""
    if conversation_history is None:
        conversation_history = []
        
    today = datetime.now().strftime("%Y-%m-%d")
    now = datetime.now().strftime("%H:%M")
    
    # تجهيز ذاكرة المحادثة (Memory)
    history_text = ""
    if conversation_history:
        history_lines = []
        for msg in conversation_history[-6:]: # نحتفظ بآخر 6 رسائل لتوفير الرصيد (Tokens)
            history_lines.append(f"المستخدم: {msg.get('user', '')}")
            if msg.get('ai'):
                history_lines.append(f"حازم: {msg.get('ai', '')}")
        history_text = "\n\n--- الذاكرة التراكمية للمحادثات السابقة ---\n" + "\n".join(history_lines) + "\n---------------------------"
    
    prompt_with_time = SYSTEM_PROMPT.replace('{today}', today).replace('{now}', now)
    full_prompt = f"{prompt_with_time}\n\n--- بيانات وسياق المستخدم الحي (مهم جداً) ---\n{context}{history_text}\n\nطلب المستخدم الحالي: {user_input}"
    
    try:
        response = client.models.generate_content(
            model='gemini-flash-lite-latest',
            contents=full_prompt
        )
        text = response.text.strip()
        
        # Extract JSON from text (in case Gemini adds markdown backticks)
        if "```json" in text:
            text = text.split("```json")[1].split("```")[0].strip()
        elif "```" in text:
            text = text.split("```")[1].split("```")[0].strip()
            
        return json.loads(text)
    except Exception as e:
        error_msg = str(e).lower()
        import traceback
        print(f"AI Engine Error: {e}\nTraceback: {traceback.format_exc()}", flush=True)
        if 'text' in locals():
            print(f"Raw Text Response: {text}", flush=True)
        
        # Check for Rate Limit (429) or Quota exceeded
        if "429" in error_msg or "quota" in error_msg or "exhausted" in error_msg:
            return {
                "action": "chat",
                "message": "معلش يا صاحبي، رصيد المحادثات خلص دلوقتي. جرب تاني كمان دقيقة."
            }
            
        return {
            "action": "chat",
            "message": "في مشكلة تقنية صغيرة عندي. جرب تبعت الرسالة تاني."
        }
